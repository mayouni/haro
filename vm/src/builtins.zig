/// The spelling a .haro file writes for the native registered as `low` (lowercase, underscores as registered), or null for no native
pub fn pascalOf(low: []const u8) ?[]const u8 {
    for (pascal) |e| if (std.mem.eql(u8, e[0], low)) return e[1];
    return null;
}

/// The registered name of a native whose name holds an underscore, from its .haro spelling in any case (`TUISize` -> `tui_size`), or null
pub fn underscoreOf(written: []const u8) ?[]const u8 {
    for (pascal) |e| {
        if (std.mem.indexOfScalar(u8, e[0], '_') == null) continue;
        if (std.ascii.eqlIgnoreCase(e[1], written)) return e[0];
    }
    return null;
}
