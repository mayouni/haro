"""The v0.3 scans (charter section 15): two properties the Compass's principles ask a guard to hold, measured over
the committed letters, sentences and court libraries.  python haro/spike/charter_scans.py   (exit 1 on any failure)

  S1  principle 13, the refusal rule: a refusal names a STATE, never a person. No refusal text -- a MESSAGE or a REFUSES
      or a SAYS of a letter, a message a court or the meta-court raises -- addresses or names the person who wrote the
      thing refused (you, your, vous, votre, the user).
  S2  principle 14: a declared language names no WIDTH. No letter outside the machine's declares a seat, a verb or a menu
      word that spells a thread, a core, a lane, a GPU, a kernel or a degree of parallelism: computation asks the engine,
      and the engine chooses. A machine letter is the exception that states the rule: a machine declares what it HAS.

Each scan is made to fail first: it runs on planted text before it reads the tree, and a scan that cannot flag its own
plant fails. The counts are pinned as floors, so a scan that quietly reads nothing cannot pass.
"""
import glob, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PLANT = '--plant' in sys.argv
fails = []


def check(ok, text):
    print(('  ok   ' if ok else '  FAIL ') + text)
    if not ok:
        fails.append(text)


PEOPLE = re.compile(r"\b(you|your|yours|yourself|vous|votre|vos|tu|toi|tes|the user|l'utilisateur)\b", re.I)
WIDTH = re.compile(r'\b(threads?|cores?|lanes?|gpus?|simd|kernels?|parallel(ism)?|widths?)\b', re.I)
STRING = re.compile(r'"([^"\n]*)"')


def haro_refusal_strings(text):
    """The strings a letter or a sentence speaks as a refusal: MESSAGE "...", MESSAGES [...], REFUSES [...], SAYS [...]."""
    out = []
    for m in re.finditer(r'\b(MESSAGES?|REFUSES|SAYS)\s*(\[[^\]]*\]|"[^"\n]*")', text):
        out += STRING.findall(m.group(2))
    return out


RING_RAISE = re.compile(r'\b(CtFail|CtFailC|StzuFail|raise)\(')


def ring_refusal_strings(text):
    out = []
    for line in text.splitlines():
        if RING_RAISE.search(line):
            out += STRING.findall(line)
    return out


def identifiers(text):
    """What a letter spells outside its strings: kinds, seats, menu words. Strings are prose; identifiers are the language."""
    return re.findall(r'[A-Za-z_][A-Za-z0-9_]*', STRING.sub('""', re.sub(r'--[^\n]*', '', text)))


# ---- the scans must fail first --------------------------------------------------------------------------------------------
planted_s1 = ['You must fix your declaration', 'vous devez corriger votre phrase', 'the user forgot the RATIONALE']
clean_s1 = ['the question carries a character this language does not use: {what}', 'RATIONALE is mandatory on every declaration']
check(all(PEOPLE.search(t) for t in planted_s1) and not any(PEOPLE.search(t) for t in clean_s1),
      'S1 the scan flags a refusal that addresses or names a person, and passes one that names a state (made to fail first)')
def widths_in(ids):
    return sorted({m.group(0).lower() for m in WIDTH.finditer(' '.join(ids))})


planted_s2 = 'DEFINE DECLARATION job AS (VERB "JOB", SEATS [threads: number, kernel: text]) RATIONALE "x"'
clean_s2 = 'DEFINE DECLARATION job AS (VERB "JOB", SEATS [steps: text]) RATIONALE "no thread and no core here"'
check(widths_in(identifiers(planted_s2)) == ['kernel', 'threads'] and not widths_in(identifiers(clean_s2)),
      'S2 the scan flags a seat that spells a width and ignores a width named only in prose (made to fail first)')

# ---- S1 ---------------------------------------------------------------------------------------------------------------------
letters = sorted(glob.glob(os.path.join(HERE, '*.haro')) + glob.glob(os.path.join(HERE, 'v*', '*.haro')))
sentences = sorted(glob.glob(os.path.join(HERE, 'n', '*.n')) + glob.glob(os.path.join(HERE, '*.z')) + glob.glob(os.path.join(HERE, 'f', '*.f')) + glob.glob(os.path.join(HERE, 'a', '*.a')))
libs = [p for p in sorted(glob.glob(os.path.join(HERE, '*.ring'))) if 'GENERATED by forge.ring' not in open(p, encoding='utf-8', errors='replace').read(400)]
strings, hits = [], []
for p in letters + sentences:
    for s in haro_refusal_strings(open(p, encoding='utf-8', errors='replace').read()):
        strings.append((os.path.relpath(p, HERE), s))
for p in libs:
    for s in ring_refusal_strings(open(p, encoding='utf-8', errors='replace').read()):
        strings.append((os.path.relpath(p, HERE), s))
if PLANT:
    strings.append(('PLANTED', 'You must fix your declaration'))
hits = [(p, s) for p, s in strings if PEOPLE.search(s)]
S1_FLOOR = 900
for p, s in hits[:5]:
    print(f'  FAIL S1 {p}: {s[:100]}')
fails.extend(f'S1 {p}' for p, _ in hits)
check(not hits and len(strings) >= S1_FLOOR,
      f'S1 {len(strings)} refusal texts read ({len(letters)} letters, {len(sentences)} sentences, {len(libs)} court libraries): {len(hits)} address or name a person, floor {S1_FLOOR}')

# ---- S2 ---------------------------------------------------------------------------------------------------------------------
machine = [p for p in letters if os.path.basename(p).startswith('machine')]
others = [p for p in letters if p not in machine]
seen, allowed, bad = 0, {}, []
for p in letters:
    ids = identifiers(open(p, encoding='utf-8', errors='replace').read())
    seen += len(ids)
    found = widths_in(ids)
    if PLANT and os.path.basename(p) == 'n_v17.haro':
        found.append('planted-thread')
    if found:
        if p in machine:
            allowed[os.path.basename(p)] = found
        else:
            bad.append((os.path.basename(p), found))
S2_FLOOR_LETTERS, S2_FLOOR_IDS = 9, 2000
for p, f in bad[:5]:
    print(f'  FAIL S2 {p}: {f}')
fails.extend(f'S2 {p}' for p, _ in bad)
check(not bad and len(others) >= S2_FLOOR_LETTERS and seen >= S2_FLOOR_IDS,
      f'S2 {len(others)} letters outside the machine\'s, {seen} identifiers read across {len(letters)}: {len(bad)} spell a width (floors {S2_FLOOR_LETTERS} letters, {S2_FLOOR_IDS} identifiers)')
check(len(machine) >= 1 and allowed,
      f'S2 the machine letters ({len(machine)}) declare what a machine HAS and are the exception that states the rule: ' + '; '.join(f'{k}: {", ".join(v)}' for k, v in sorted(allowed.items())))

print(f'charter_scans: {"FAIL" if fails else "PASS"} ({len(fails)} failure(s))')
sys.exit(1 if fails else 0)
